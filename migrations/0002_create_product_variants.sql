-- Product variants (pv_* + pu_* + pv_counts flattened from the Mongo shape).
-- One product can have many variants (different pack sizes/units).
CREATE TABLE IF NOT EXISTS product_variants (
  pv_id                         BIGINT UNSIGNED NOT NULL PRIMARY KEY,
  p_id                          BIGINT UNSIGNED NOT NULL,
  pv_medicine_id                BIGINT UNSIGNED NULL,
  pv_sku                        VARCHAR(100)    NOT NULL DEFAULT '',
  pv_mrp                        DECIMAL(12,2)   NOT NULL DEFAULT 0,
  pv_b2c_mrp                    DECIMAL(12,2)   NOT NULL DEFAULT 0,
  pv_b2b_mrp                    DECIMAL(12,2)   NOT NULL DEFAULT 0,
  pv_b2c_price                  DECIMAL(12,2)   NOT NULL DEFAULT 0,
  pv_b2c_discounted_price       DECIMAL(12,2)   NOT NULL DEFAULT 0,
  pv_b2b_price                  DECIMAL(12,2)   NOT NULL DEFAULT 0,
  pv_b2b_discounted_price       DECIMAL(12,2)   NOT NULL DEFAULT 0,
  pv_purchase_price             DECIMAL(12,2)   NOT NULL DEFAULT 0,
  pv_stock_status               TINYINT         NOT NULL DEFAULT 0,
  pv_allow_purchase             TINYINT         NOT NULL DEFAULT 0,
  pv_allow_sales                TINYINT         NOT NULL DEFAULT 0,
  pv_b2b_discount_percent       DECIMAL(6,2)    NOT NULL DEFAULT 0,
  pv_b2c_discount_percent       DECIMAL(6,2)    NOT NULL DEFAULT 0,
  pv_b2b_min_qty                INT             NOT NULL DEFAULT 0,
  pv_b2b_max_qty                INT             NOT NULL DEFAULT 0,
  pv_b2c_min_qty                INT             NOT NULL DEFAULT 0,
  pv_b2c_max_qty                INT             NOT NULL DEFAULT 0,
  pv_average_rating             DECIMAL(3,2)    NOT NULL DEFAULT 0,
  pv_total_rating               INT             NOT NULL DEFAULT 0,
  pv_trending_score             DOUBLE          NOT NULL DEFAULT 0,
  pv_m_percentage               DECIMAL(6,2)    NOT NULL DEFAULT 0,
  pv_campaign_tag_id            BIGINT UNSIGNED NULL,
  pv_created_at                 VARCHAR(40)     NULL,
  pu_base_unit_label            VARCHAR(50)     NOT NULL DEFAULT '',
  pu_base_unit_multiplier       DOUBLE          NOT NULL DEFAULT 1,
  pu_b2b_sales_unit_label       VARCHAR(50)     NOT NULL DEFAULT '',
  pu_b2c_sales_unit_label       VARCHAR(50)     NOT NULL DEFAULT '',
  pu_b2c_base_unit_multiplier   DOUBLE          NOT NULL DEFAULT 1,
  pu_b2b_base_unit_multiplier   DOUBLE          NOT NULL DEFAULT 1,
  pu_b2c_sales_unit_id          BIGINT UNSIGNED NULL,
  pu_b2b_sales_unit_id          BIGINT UNSIGNED NULL,
  pvc_viewed_count              INT             NOT NULL DEFAULT 0,
  pvc_ordered_count             INT             NOT NULL DEFAULT 0,
  pvc_wishlist_count            INT             NOT NULL DEFAULT 0,
  sort_order                    INT             NOT NULL DEFAULT 0,
  created_at                    TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at                    TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

  KEY idx_p_id (p_id),
  CONSTRAINT fk_variant_product FOREIGN KEY (p_id) REFERENCES products(p_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
