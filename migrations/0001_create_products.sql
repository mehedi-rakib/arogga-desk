-- Core product table. One row per p_id (matches the upstream Arogga catalog).
CREATE TABLE IF NOT EXISTS products (
  p_id                          BIGINT UNSIGNED NOT NULL PRIMARY KEY,
  p_name                        VARCHAR(500)    NOT NULL DEFAULT '',
  p_name_bn                     VARCHAR(500)    NOT NULL DEFAULT '',
  p_generic_name                VARCHAR(500)    NOT NULL DEFAULT '',
  p_type                        VARCHAR(100)    NOT NULL DEFAULT '',
  p_brand                       VARCHAR(255)    NOT NULL DEFAULT '',
  p_brand_name                  VARCHAR(255)    NOT NULL DEFAULT '',
  p_brand_id                    BIGINT UNSIGNED NULL,
  p_form                        VARCHAR(100)    NOT NULL DEFAULT '',
  p_strength                    VARCHAR(100)    NOT NULL DEFAULT '',
  p_short_description           TEXT,
  p_meta_description            TEXT,
  p_active_status               VARCHAR(20)     NOT NULL DEFAULT '',
  p_allow_sales                 TINYINT         NOT NULL DEFAULT 0,
  p_is_flash_sale               TINYINT         NOT NULL DEFAULT 0,
  p_cat_id                      BIGINT UNSIGNED NULL,
  p_cold                        TINYINT         NOT NULL DEFAULT 0,
  p_is_not_allowed_outside_dhaka TINYINT        NOT NULL DEFAULT 0,
  p_trending_score              DOUBLE          NOT NULL DEFAULT 0,
  p_created_at                  VARCHAR(40)     NULL,
  p_rx_req                      TINYINT         NOT NULL DEFAULT 0,
  p_generic_id                  BIGINT UNSIGNED NULL,
  p_manufacturer_id             BIGINT UNSIGNED NULL,
  p_company_id                  BIGINT UNSIGNED NULL,
  p_variant_count               INT             NOT NULL DEFAULT 0,
  p_weight                      DOUBLE          NOT NULL DEFAULT 0,
  p_stock_status                TINYINT         NOT NULL DEFAULT 0,
  poster                        VARCHAR(1000)   NOT NULL DEFAULT '',
  have_image                    TINYINT         NOT NULL DEFAULT 0,
  product_count_viewed          INT             NOT NULL DEFAULT 0,
  product_count_ordered         INT             NOT NULL DEFAULT 0,
  product_count_wishlist        INT             NOT NULL DEFAULT 0,
  created_at                    TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at                    TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

  FULLTEXT KEY ft_search (p_name, p_name_bn, p_generic_name, p_brand_name),
  KEY idx_brand_name (p_brand_name),
  KEY idx_cat_id (p_cat_id),
  KEY idx_trending (p_trending_score),
  KEY idx_active_status (p_active_status),
  KEY idx_ordered_count (product_count_ordered)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
